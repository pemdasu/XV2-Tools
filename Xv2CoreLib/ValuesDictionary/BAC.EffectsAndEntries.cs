        //Bac PhysicsObjectControl
        public static Dictionary<ushort, string> PhysicsObjectControlType { get; private set; } = new Dictionary<ushort, string>()
        {
            { 0 , $"{GetPhysicsObjectFunctionName(0)} (0)" },
            { 1 , $"{GetPhysicsObjectFunctionName(1)} (1)" },
            { 2 , $"{GetPhysicsObjectFunctionName(2)} (2)" },
            { 1026 , $"{GetPhysicsObjectFunctionName(1026)} (1026)" }, //Used in Super Gamma Blast
        };

        public static string GetPhysicsObjectFunctionName(ushort function)
        {
            switch (function & 0xFF)
            {
                case 0: return "SCD Flag";
                case 1: return "SCD Vector";
                case 2: return "Play SCD Animation";
                default: return "Unknown";
            }
        }

